///////////////////////////////////////////////////////////////
// STATUS
///////////////////////////////////////////////////////////////

export type PreselectionStatus =
  | "PENDING"
  | "UNDER_REVIEW"
  | "APPROVED"
  | "REJECTED"
  | "NEEDS_REVIEW";

///////////////////////////////////////////////////////////////
// REVIEW ACTION
///////////////////////////////////////////////////////////////

export type ReviewAction =
  | "approve"
  | "reject"
  | "comment";

///////////////////////////////////////////////////////////////
// PRESELECTION
///////////////////////////////////////////////////////////////

export interface PreselectionCandidate {

  /////////////////////////////////////////////////////////////
  // IDENTIFICATION
  /////////////////////////////////////////////////////////////

  id: string;

  applicationId: string;

  candidateId: string;

  jobId: string;

  /////////////////////////////////////////////////////////////
  // PROFILE
  /////////////////////////////////////////////////////////////

  fullName: string;

  email: string;

  phone?: string;

  avatar?: string;

  location?: string;

  /////////////////////////////////////////////////////////////
  // PROFESSIONAL
  /////////////////////////////////////////////////////////////

  title?: string;

  experienceYears: number;

  skills: string[];

  education?: string;

  /////////////////////////////////////////////////////////////
  // DOCUMENTS
  /////////////////////////////////////////////////////////////

  cvUrl?: string;

  oralPresentationUrl?: string;

  /////////////////////////////////////////////////////////////
  // AI
  /////////////////////////////////////////////////////////////

  aiScore: number;

  cvScore?: number;

  quizScore?: number;

  presentationScore?: number;

  /////////////////////////////////////////////////////////////
  // PRESELECTION
  /////////////////////////////////////////////////////////////

  isPreselected: boolean;

  preselectionScore?: number;

  preselectionComment?: string;

  status: PreselectionStatus;

  /////////////////////////////////////////////////////////////
  // REVIEW
  /////////////////////////////////////////////////////////////

  preselectedBy?: string;

  preselectedAt?: string;

  /////////////////////////////////////////////////////////////
  // DATES
  /////////////////////////////////////////////////////////////

  appliedAt: string;

  updatedAt?: string;

}

///////////////////////////////////////////////////////////////
// COMMENT
///////////////////////////////////////////////////////////////

export interface PreselectionComment {

  id: string;

  applicationId: string;

  reviewer: string;

  comment: string;

  createdAt: string;

}

///////////////////////////////////////////////////////////////
// HISTORY
///////////////////////////////////////////////////////////////

export interface PreselectionHistory {

  id: string;

  applicationId: string;

  action: ReviewAction;

  reviewer: string;

  comment?: string;

  createdAt: string;

}

///////////////////////////////////////////////////////////////
// FILTERS
///////////////////////////////////////////////////////////////

export interface PreselectionFilters {

  status: string;

  reviewer: string;

  minimumAIScore: number;

  location: string;

  search: string;

}

///////////////////////////////////////////////////////////////
// STATISTICS
///////////////////////////////////////////////////////////////

export interface PreselectionStatistics {

  pending: number;

  approved: number;

  rejected: number;

  needsReview: number;

  averageAIScore: number;

  averageReviewTime: number;

}

///////////////////////////////////////////////////////////////
// PAGINATION
///////////////////////////////////////////////////////////////

export interface PreselectionPagination {

  page: number;

  pageSize: number;

  totalItems: number;

  totalPages: number;

}

///////////////////////////////////////////////////////////////
// RESPONSE
///////////////////////////////////////////////////////////////

export interface PreselectionResponse {

  candidates: PreselectionCandidate[];

  statistics: PreselectionStatistics;

  pagination?: PreselectionPagination;

}

///////////////////////////////////////////////////////////////
// DASHBOARD
///////////////////////////////////////////////////////////////

export interface PreselectionDashboard {

  statistics: PreselectionStatistics;

  pendingCandidates: PreselectionCandidate[];

  approvedCandidates: PreselectionCandidate[];

  rejectedCandidates: PreselectionCandidate[];

}

///////////////////////////////////////////////////////////////
// REVIEW REQUEST
///////////////////////////////////////////////////////////////

export interface ReviewRequest {

  applicationId: string;

  action: ReviewAction;

  comment?: string;

}

///////////////////////////////////////////////////////////////
// REVIEW RESPONSE
///////////////////////////////////////////////////////////////

export interface ReviewResponse {

  success: boolean;

  message: string;

  candidate: PreselectionCandidate;

}

///////////////////////////////////////////////////////////////
