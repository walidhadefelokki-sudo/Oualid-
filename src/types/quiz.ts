///////////////////////////////////////////////////////////////
// QUIZ OPTION
///////////////////////////////////////////////////////////////

export interface QuizOption {
  id: string;
  text: string;
}

///////////////////////////////////////////////////////////////
// QUESTION
///////////////////////////////////////////////////////////////

export interface QuizQuestion {
  id: string;

  question: string;

  options: QuizOption[];

  correctAnswer?: string;

  explanation?: string;

  difficulty?: "easy" | "medium" | "hard";

  category?: string;

  weight?: number;
}

///////////////////////////////////////////////////////////////
// QUIZ
///////////////////////////////////////////////////////////////

export interface Quiz {
  id: string;

  applicationId: string;

  title: string;

  description?: string;

  duration: number;

  passingScore: number;

  questions: QuizQuestion[];

  createdAt?: string;

  updatedAt?: string;
}

///////////////////////////////////////////////////////////////
// ANSWERS
///////////////////////////////////////////////////////////////

export type QuizAnswers = Record<string, string>;

///////////////////////////////////////////////////////////////
// SUMMARY
///////////////////////////////////////////////////////////////

export interface QuizSummary {

  totalQuestions: number;

  answeredQuestions: number;

  unansweredQuestions: number;

  correctAnswers: number;

  incorrectAnswers: number;

  score: number;

  passed: boolean;

}

///////////////////////////////////////////////////////////////
// RESULT
///////////////////////////////////////////////////////////////

export interface QuizResult {

  score: number;

  weightedScore?: number;

  grade?: string;

  performance?: string;

  passed: boolean;

  correctAnswers: number;

  incorrectAnswers: number;

  unansweredQuestions: number;

}

///////////////////////////////////////////////////////////////
// TIMER
///////////////////////////////////////////////////////////////

export interface QuizTimerState {

  totalTime: number;

  remainingTime: number;

  elapsedTime: number;

  percentage: number;

  isExpired: boolean;

  isWarning: boolean;

  isCritical: boolean;

}

///////////////////////////////////////////////////////////////
// QUESTION STATUS
///////////////////////////////////////////////////////////////

export type QuestionStatus =
  | "answered"
  | "unanswered"
  | "current";

///////////////////////////////////////////////////////////////
// QUIZ STATUS
///////////////////////////////////////////////////////////////

export type QuizStatus =
  | "idle"
  | "loading"
  | "ready"
  | "running"
  | "paused"
  | "completed"
  | "submitted"
  | "expired"
  | "error";

