  languages?: string[];

  /////////////////////////////////////////////////////////////
  // DOCUMENTS
  /////////////////////////////////////////////////////////////

  cvUrl?: string;

  oralPresentationUrl?: string;

  /////////////////////////////////////////////////////////////
  // AI SCORES
  /////////////////////////////////////////////////////////////

  aiScore: number;

  cvScore?: number;

  quizScore?: number;

  presentationScore?: number;

  experienceScore?: number;

  skillsScore?: number;

  rankingScore?: number;

